package com.otter.app.util

import android.content.Context
import android.webkit.CookieManager
import android.database.sqlite.SQLiteDatabase
import android.database.sqlite.SQLiteDatabase.OPEN_READONLY
import com.otter.app.data.model.Cookie
import java.io.File

object CookieHelper {

    private const val COOKIE_FILE_NAME = "cookies.txt"
    private const val COOKIE_HEADER = "# Netscape HTTP Cookie File\n# Auto-generated by Otter\n"

    private val SCHEME = object {
        val HOST = "host_key"
        val NAME = "name"
        val VALUE = "value"
        val PATH = "path"
        val SECURE = "is_secure"
        val EXPIRY = "expires_utc"
    }

    fun Context.getCookiesFile(): File = File(cacheDir, COOKIE_FILE_NAME)

    fun getCookieListFromDatabase(context: Context): Result<List<Cookie>> = runCatching {
        CookieManager.getInstance().run {
            if (!hasCookies()) throw Exception("No cookies in database")
            flush()
        }

        val dbPath = context.dataDir.resolve("app_webview/Default/Cookies").absolutePath
        val db = SQLiteDatabase.openDatabase(dbPath, null, OPEN_READONLY)

        try {
            val projection = arrayOf(
                SCHEME.HOST, SCHEME.EXPIRY, SCHEME.PATH,
                SCHEME.NAME, SCHEME.VALUE, SCHEME.SECURE
            )
            val cookieList = mutableListOf<Cookie>()

            db.query("cookies", projection, null, null, null, null, null).use { cursor ->
                while (cursor.moveToNext()) {
                    val expiry = cursor.getLong(cursor.getColumnIndexOrThrow(SCHEME.EXPIRY))
                    val name = cursor.getString(cursor.getColumnIndexOrThrow(SCHEME.NAME)) ?: continue
                    val value = cursor.getString(cursor.getColumnIndexOrThrow(SCHEME.VALUE)) ?: continue
                    val path = cursor.getString(cursor.getColumnIndexOrThrow(SCHEME.PATH)) ?: "/"
                    val secure = cursor.getLong(cursor.getColumnIndexOrThrow(SCHEME.SECURE)) == 1L
                    var hostKey = cursor.getString(cursor.getColumnIndexOrThrow(SCHEME.HOST)) ?: continue
                    if (hostKey[0] != '.') hostKey = ".$hostKey"

                    cookieList.add(
                        Cookie(
                            domain = hostKey,
                            name = name,
                            value = value,
                            path = path,
                            secure = secure,
                            expiry = expiry
                        )
                    )
                }
            }

            cookieList
        } finally {
            db.close()
        }
    }

    fun List<Cookie>.toCookiesFileContent(): String {
        return this.fold(StringBuilder(COOKIE_HEADER)) { acc, cookie ->
            acc.append(cookie.toNetscapeCookieString()).append("\n")
        }.toString()
    }

    fun getCookiesContentFromDatabase(context: Context): Result<String> =
        getCookieListFromDatabase(context).mapCatching { it.toCookiesFileContent() }

    fun writeCookiesFile(context: Context, content: String) {
        context.getCookiesFile().writeText(content)
    }

    fun getCookieContentFromPrefs(context: Context): String? {
        val file = context.getCookiesFile()
        return if (file.exists()) file.readText() else null
    }
}
