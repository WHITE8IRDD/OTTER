package com.otter.app.data.cookies

import android.content.Context
import java.io.File

class CookieManager(private val context: Context) {

    companion object {
        private const val COOKIE_FILE_NAME = "cookies.txt"
        private const val HEADER = "# Netscape HTTP Cookie File\n# Auto-generated by Otter\n"
    }

    private fun getCookieFile(): File = File(context.filesDir, COOKIE_FILE_NAME)

    fun save(cookieContent: String) {
        val content = if (cookieContent.startsWith("#")) cookieContent else "$HEADER$cookieContent"
        getCookieFile().writeText(content)
    }

    fun load(): String? {
        val file = getCookieFile()
        return if (file.exists()) file.readText() else null
    }

    fun exists(): Boolean {
        val file = getCookieFile()
        return file.exists() && file.length() > 0
    }

    fun delete() {
        getCookieFile().delete()
    }

    fun getCookieFilePath(): String = getCookieFile().absolutePath
}
