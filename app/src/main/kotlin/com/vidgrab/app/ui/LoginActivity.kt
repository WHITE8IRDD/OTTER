package com.vidgrab.app.ui

import android.annotation.SuppressLint
import android.graphics.Bitmap
import android.os.Bundle
import android.util.Log
import android.view.ViewGroup
import android.webkit.*
import android.widget.Toast
import androidx.activity.ComponentActivity
import com.vidgrab.app.data.cookies.CookieManager
import java.net.URLDecoder

class LoginActivity : ComponentActivity() {

    companion object {
        private const val TAG = "LoginActivity"
        private const val INSTA_URL = "https://www.instagram.com"
    }

    private lateinit var webView: WebView
    private var captured = false
    private var pageLoads = 0

    @SuppressLint("SetJavaScriptEnabled")
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        webView = WebView(this).apply {
            layoutParams = ViewGroup.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT,
                ViewGroup.LayoutParams.MATCH_PARENT
            )
            settings.javaScriptEnabled = true
            settings.domStorageEnabled = true
            settings.userAgentString =
                "Mozilla/5.0 (Linux; Android 12) AppleWebKit/537.36 Chrome/120.0.0.0 Mobile Safari/537.36"

            webViewClient = object : WebViewClient() {
                override fun onPageStarted(view: WebView?, url: String?, favicon: Bitmap?) {
                    Log.i(TAG, "Page: $url")
                }
                override fun onPageFinished(view: WebView?, url: String?) {
                    pageLoads++
                    // Check after each page load (login redirect may take multiple hops)
                    webView.postDelayed({ checkAndCapture() }, 2000)
                }
            }

            webChromeClient = object : WebChromeClient() {
                override fun onConsoleMessage(msg: ConsoleMessage?): Boolean {
                    msg?.let { Log.i(TAG, "JS[${it.messageLevel()}]: ${it.message()}") }
                    return true
                }
            }

            loadUrl("$INSTA_URL/accounts/login/")
        }

        setContentView(webView)
    }

    private fun checkAndCapture() {
        if (captured) return
        val cm = android.webkit.CookieManager.getInstance()
        val cookieStr = cm.getCookie(INSTA_URL) ?: ""
        Log.i(TAG, "Cookies: $cookieStr")

        val pairs = cookieStr.split(";").map { it.trim() }
        val sessionId = pairs.find { it.startsWith("sessionid=") && it.length > "sessionid=".length }

        if (sessionId != null) {
            saveCookies(pairs)
            cm.flush()
            captured = true
            runOnUiThread {
                Toast.makeText(this, "Cookies saved!", Toast.LENGTH_LONG).show()
            }
            webView.postDelayed({ finish() }, 1500)
        }
    }

    private fun saveCookies(pairs: List<String>) {
        val lines = mutableListOf(
            "# Netscape HTTP Cookie File",
            "# Auto-generated by Otter Login"
        )
        for (pair in pairs) {
            val parts = pair.split("=", limit = 2)
            if (parts.size == 2) {
                val name = parts[0]
                val value = try { URLDecoder.decode(parts[1], "UTF-8") } catch (_: Exception) { parts[1] }
                lines.add(".instagram.com\tTRUE\t/\tTRUE\t2147483647\t$name\t$value")
            }
        }
        CookieManager(this).save(lines.joinToString("\n"))
        Log.i(TAG, "Saved ${pairs.size} cookies")
    }
}
